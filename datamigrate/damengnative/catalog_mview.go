// materializedSnapshot keeps the actual stored snapshot, including an
// intentionally stale MV. Re-running its SELECT is not a data migration.
func (r *catalogReader) materializedSnapshot(position int, ddl string) error {
	mv := r.snapshot.Objects[position]
	state, refresh, err := materializedOptions(ddl)
	if err != nil {
		return fmt.Errorf("物化视图 %s: %w", mv.Name, err)
	}
	if state.RefreshMethod == "FAST" || state.RefreshMethod == "FORCE" {
		if err = r.proveMaterializedCurrent(mv.Name, state); err != nil {
			return err
		}
		state.Baseline = true
	}
	var raw catalogObject
	for id, indices := range r.byRaw {
		for _, i := range indices {
			if i == position {
				raw = r.raw[id]
			}
		}
	}
	var backing catalogObject
	prebuiltID := int64(uint32(raw.info3))
	if t, ok := r.raw[prebuiltID]; ok && t.sub == "UTAB" {
		backing = t
	}
	if backing.id == 0 {
		// INFO2 is the query's base table, not the snapshot table. DM8's
		// documented generated storage name is MTAB$_<mview_name>.
		for _, t := range r.raw {
			if t.name == "MTAB$_"+mv.Name && t.sub == "UTAB" {
				backing = t
				break
			}
		}
	}
	if backing.id == 0 {
		// Probe the compatible view rather than assuming optional SYS offsets.
		var name string
		if err := r.db.QueryRowContext(r.ctx, `SELECT CONTAINER_NAME FROM ALL_MVIEWS WHERE OWNER=? AND MVIEW_NAME=?`, r.schema, mv.Name).Scan(&name); err != nil {
			return fmt.Errorf("物化视图 %s 的快照承载表关系不可读取: %w", mv.Name, err)
		}
		for _, t := range r.raw {
			if t.name == name && t.sub == "UTAB" {
				backing = t
				break
			}
		}
	}
	if backing.id == 0 {
		return fmt.Errorf("物化视图 %s 无可确认的快照承载表，不能用刷新替代迁移", mv.Name)
	}
	storageName := backing.name
	if prebuiltID == 0 {
		// DM forbids user CREATE TABLE with MTAB$_ and MLOG$_ prefixes. Create
		// legal, deterministic prebuilt storage, while reading the original name.
		storageName = "DBGOLD_MV_" + Fingerprint([]string{r.schema, mv.Name})[:20]
		if _, exists := r.index["table\x00"+storageName]; exists {
			return fmt.Errorf("物化视图 %s 的快照承载名称 %s 已被源对象占用", mv.Name, storageName)
		}
		storageDDL, err := r.getDDL("TABLE", backing.name)
		if err != nil {
			return fmt.Errorf("物化视图 %s 的快照承载表 DDL 不可读取: %w", mv.Name, err)
		}
		storageDDL, err = renameDDLHead(storageDDL, "TABLE", r.schema, storageName)
		if err != nil {
			return err
		}
		helper := Object{Kind: "table", Name: storageName, Schema: r.schema, Table: backing.name, Dependencies: []string{}, Units: []Unit{{SQL: storageDDL, Phase: "before_data"}}, DropSQL: "DROP TABLE " + Qualified(r.schema, storageName) + " CASCADE CONSTRAINTS"}
		h := r.add(0, helper)
		var indexes []struct {
			position int
			ddl      string
		}
		for id, child := range r.raw {
			if child.pid != backing.id || child.sub != "INDEX" && child.sub != "CNTIND" {
				continue
			}
			for _, j := range r.byRaw[id] {
				if r.snapshot.Objects[j].Managed {
					continue
				}
				kind, _, _, _ := ddlOptions(r.snapshot.Objects[j])
				indexDDL, e := r.getDDL(kind, child.name)
				if e != nil {
					return fmt.Errorf("物化视图 %s 用户索引 %s 不可读取: %w", mv.Name, child.name, e)
				}
				indexDDL, e = rebindMaterializedIndex(indexDDL, r.schema, backing.name, storageName)
				if e != nil {
					return fmt.Errorf("物化视图 %s 用户索引 %s: %w", mv.Name, child.name, e)
				}
				indexes = append(indexes, struct {
					position int
					ddl      string
				}{j, indexDDL})
			}
		}
		// The original backing tree is generated by its parent in the source.
		// Keep it inventoried, but do not independently replay it on the target.
		r.markManagedTree(backing.id, mv.ID)
		for _, index := range indexes {
			o := &r.snapshot.Objects[index.position]
			o.Managed = false
			o.Generated = false
			o.ParentID = r.snapshot.Objects[h].ID
			o.Table = storageName
			o.Dependencies = appendUnique(o.Dependencies, r.snapshot.Objects[h].ID)
			o.Units = []Unit{{SQL: index.ddl, Phase: "after_data"}}
		}
		for id, raw := range r.raw {
			if raw.sub == "TRIG" && raw.info1&32 != 0 && raw.name == "MTRG_REFRESH_MVIEW_"+strconv.FormatInt(backing.id, 10) {
				for _, j := range r.byRaw[id] {
					r.snapshot.Objects[j].Managed = true
					r.snapshot.Objects[j].Generated = true
					r.snapshot.Objects[j].ParentID = mv.ID
					r.snapshot.Objects[j].Units = nil
				}
			}
		}
		r.snapshot.Objects[position].Dependencies = appendUnique(r.snapshot.Objects[position].Dependencies, r.snapshot.Objects[h].ID)
	}
	bound, err := bindPrebuiltMV(ddl, r.schema, storageName)
	if err != nil {
		return fmt.Errorf("物化视图 %s: %w", mv.Name, err)
	}
	// Timed and ON COMMIT refreshes must not replace the copied snapshot while
	// the migration is still loading dependent objects. Restore the exact native
	// policy only after the explicit baseline and all ordinary user triggers.
	bound, err = materializedWithoutRefresh(bound)
	if err != nil {
		return err
	}
	r.snapshot.Objects[position].Materialized = state
	r.snapshot.Objects[position].Table = storageName
	r.snapshot.Objects[position].Units = []Unit{{SQL: bound, Phase: "after_data"}}
	if state.Baseline {
		r.snapshot.Objects[position].Units = append(r.snapshot.Objects[position].Units, Unit{SQL: "ALTER MATERIALIZED VIEW " + Qualified(r.schema, mv.Name) + " REFRESH COMPLETE ON DEMAND", Phase: "mv_prepare"})
		r.snapshot.Objects[position].Units = append(r.snapshot.Objects[position].Units, Unit{SQL: MaterializedBaselineSQL(r.schema, mv.Name), Phase: "mv_rebase"})
		reason := "将逐行复制当前物化快照；目标端在前后多重集一致性核验通过后执行 COMPLETE 初始化新日志基线，保留原 " + state.RefreshMethod + " 刷新策略，不刷新源端；源端旧日志历史由新基线替代"
		if len(state.RowIDColumns) > 0 {
			reason += "；仅直接 ROWID 输出会映射为目标物理 ROWID，普通列值和重复行数量保持不变"
		}
		r.snapshot.Issues = append(r.snapshot.Issues, Issue{ObjectID: mv.ID, Kind: mv.Kind, Name: mv.Name, Severity: "warning", Reason: reason})
	}
	r.snapshot.Objects[position].Units = append(r.snapshot.Objects[position].Units, Unit{SQL: "ALTER MATERIALIZED VIEW " + Qualified(r.schema, mv.Name) + " " + refresh, Phase: "mv_restore"})
	return nil
}

func rebindMaterializedIndex(ddl, schema, old, new string) (string, error) {
	ts, err := nativeTokens(ddl)
	if err != nil {
		return "", err
	}
	for i, t := range ts {
		if t.kind != 'i' || !strings.EqualFold(t.value, "ON") {
			continue
		}
		if i+1 >= len(ts) {
			return "", fmt.Errorf("索引 ON 对象缺失")
		}
		j := i + 1
		end := ts[j].end
		if j+2 < len(ts) && ts[j+1].value == "." {
			if ts[j].value != schema || ts[j+2].value != old {
				return "", fmt.Errorf("索引 ON 对象不属于已确认的物化存储表")
			}
			end = ts[j+2].end
		} else if ts[j].value != old {
			return "", fmt.Errorf("索引 ON 对象不属于已确认的物化存储表")
		}
		return ddl[:ts[j].start] + Qualified(schema, new) + ddl[end:], nil
	}
	return "", fmt.Errorf("索引定义缺少 ON 物化存储对象")
}

func MaterializedBaselineSQL(schema, name string) string {
	return "REFRESH MATERIALIZED VIEW " + Qualified(schema, name) + " COMPLETE"
}

func MaterializedPolicy(ddl string) (string, error) {
	_, policy, err := materializedOptions(ddl)
	return policy, err
}

// materializedOptions only reads the declaration, never keywords in the query
// or string literals. Options may be ordered arbitrarily by GET_DDL.
func materializedOptions(ddl string) (*MaterializedState, string, error) {
	ts, err := nativeTokens(ddl)
	if err != nil {
		return nil, "", err
	}
	as, refresh, depth := -1, -1, 0
	state := &MaterializedState{RefreshMethod: "FORCE", RefreshRule: "PRIMARY KEY"}
	for i, t := range ts {
		if t.value == "(" {
			depth++
			continue
		}
		if t.value == ")" {
			depth--
			continue
		}
		if depth != 0 || t.kind != 'i' {
			continue
		}
		word := strings.ToUpper(t.value)
		if word == "AS" {
			as = i
			break
		}
		if word == "NEVER" && i+1 < len(ts) && strings.EqualFold(ts[i+1].value, "REFRESH") {
			state.RefreshMethod = "NEVER"
			if refresh < 0 {
				refresh = i
			}
			continue
		}
		if word == "REFRESH" && refresh < 0 {
			refresh = i
		}
		if word == "FAST" || word == "COMPLETE" || word == "FORCE" {
			state.RefreshMethod = word
		}
		if word == "WITH" && i+1 < len(ts) && strings.EqualFold(ts[i+1].value, "ROWID") {
			state.RefreshRule = "ROWID"
		}
	}
	if as < 0 || as+1 >= len(ts) {
		return nil, "", fmt.Errorf("缺少物化视图查询 AS")
	}
	state.Query = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(ddl[ts[as+1].start:]), ";"))
	if _, err = MaterializedBagSQL("S", "V", state.Query, []string{"C"}, nil); err != nil {
		return nil, "", err
	}
	policy := "REFRESH FORCE ON DEMAND"
	if refresh >= 0 {
		policy = strings.TrimSpace(ddl[ts[refresh].start:ts[as].start])
	} else {
		// QUERY REWRITE is independent of refresh and follows storage options.
		for i, t := range ts[:as] {
			if t.kind == 'i' && (strings.EqualFold(t.value, "ENABLE") || strings.EqualFold(t.value, "DISABLE")) && i+1 < as && strings.EqualFold(ts[i+1].value, "QUERY") {
				policy += " " + strings.TrimSpace(ddl[t.start:ts[as].start])
				break
			}
		}
	}
	return state, policy, nil
}

func materializedWithoutRefresh(ddl string) (string, error) {
	ts, err := nativeTokens(ddl)
	if err != nil {
		return "", err
	}
	as, start, depth := -1, -1, 0
	for i, t := range ts {
		if t.value == "(" {
			depth++
			continue
		}
		if t.value == ")" {
			depth--
			continue
		}
		if depth != 0 || t.kind != 'i' {
			continue
		}
		if strings.EqualFold(t.value, "AS") {
			as = i
			break
		}
		if start < 0 && (strings.EqualFold(t.value, "REFRESH") || strings.EqualFold(t.value, "NEVER") || strings.EqualFold(t.value, "ENABLE") || strings.EqualFold(t.value, "DISABLE")) {
			start = i
		}
	}
	if as < 0 {
		return "", fmt.Errorf("物化视图缺少 AS")
	}
	if start < 0 {
		start = as
	}
	return ddl[:ts[start].start] + "NEVER REFRESH " + ddl[ts[as].start:], nil
}

func (r *catalogReader) proveMaterializedCurrent(name string, state *MaterializedState) error {
	conn, err := r.db.Conn(r.ctx)
	if err != nil {
		return err
	}
	defer func() { _ = conn.Raw(func(any) error { return driver.ErrBadConn }); _ = conn.Close() }()
	if _, err = conn.ExecContext(r.ctx, "SET SCHEMA "+Quote(r.schema)); err != nil {
		return fmt.Errorf("物化视图 %s 只读核验会话模式不可设置: %w", name, err)
	}
	tx, err := conn.BeginTx(r.ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	// Server-enforced read-only mode also prevents a user function called from
	// the MV SELECT from changing source rows while proving the snapshot.
	if _, err = tx.ExecContext(r.ctx, "SET TRANSACTION READ ONLY"); err != nil {
		return fmt.Errorf("物化视图 %s 只读事务不可设置: %w", name, err)
	}
	rows, err := tx.QueryContext(r.ctx, "SELECT * FROM "+Qualified(r.schema, name)+" WHERE 1=0")
	if err != nil {
		return fmt.Errorf("物化视图 %s 输出列不可读取: %w", name, err)
	}
	state.SnapshotColumns, err = rows.Columns()
	_ = rows.Close()
	if err != nil {
		return err
	}
	state.RowIDColumns, err = materializedDirectRowIDs(state.Query, len(state.SnapshotColumns))
	if err != nil {
		return fmt.Errorf("物化视图 %s 无法安全映射 ROWID: %w", name, err)
	}
	if len(state.RowIDColumns) > 0 {
		// An object attribute called ROWID is an ordinary value. Require the
		// database's own output type proof before permitting physical rebasing.
		types, e := tx.QueryContext(r.ctx, `SELECT COLUMN_NAME,DATA_TYPE FROM ALL_TAB_COLUMNS WHERE OWNER=? AND TABLE_NAME=? ORDER BY COLUMN_ID`, r.schema, name)
		if e != nil {
			return fmt.Errorf("物化视图 %s ROWID 输出类型不可读取: %w", name, e)
		}
		actual := map[string]string{}
		for types.Next() {
			var col, kind string
			if e = types.Scan(&col, &kind); e != nil {
				_ = types.Close()
				return e
			}
			actual[col] = kind
		}
		e = types.Err()
		_ = types.Close()
		if e != nil {
			return e
		}
		for _, i := range state.RowIDColumns {
			if !strings.EqualFold(actual[state.SnapshotColumns[i]], "ROWID") {
				return fmt.Errorf("物化视图 %s 的输出 %s 未被目录证明为 ROWID，不能忽略普通属性值", name, state.SnapshotColumns[i])
			}
		}
	}
	if err = CheckMaterializedBag(r.ctx, tx, r.schema, name, state.Query, state.SnapshotColumns, nil); err != nil {
		return fmt.Errorf("物化视图 %s 的 %s 快照不能建立无损增量基线: %w；陈旧快照必须同时保留原变化日志及每视图刷新水位，DM8 公开 REFRESH/COMPILE 接口不能注册旧水位；请先由业务确认快照可刷新，或使用保留物理状态的数据库备份还原", name, state.RefreshMethod, err)
	}
	state.Staleness = "PROVEN_CURRENT"
	return nil
}

// MaterializedBagSQL uses an ordinal derived-column list so explicit MV column
// aliases and duplicate query headings do not change the comparison. COUNT in
// each group proves multiplicity as well as values (MINUS alone would not).
func MaterializedBagSQL(schema, name, query string, columns []string, ignore []int) (string, error) {
	if schema == "" || name == "" || len(columns) == 0 {
		return "", fmt.Errorf("物化视图多重集核验缺少模式、对象名或输出列")
	}
	ts, err := nativeTokens(query)
	if err != nil {
		return "", err
	}
	if len(ts) == 0 || !strings.EqualFold(ts[0].value, "SELECT") && !strings.EqualFold(ts[0].value, "WITH") {
		return "", fmt.Errorf("物化视图核验只允许完整 SELECT 查询")
	}
	for _, t := range ts {
		if t.value == ";" {
			return "", fmt.Errorf("物化视图查询不能包含多条语句")
		}
	}
	ignored := map[int]bool{}
	for _, i := range ignore {
		if i < 0 || i >= len(columns) {
			return "", fmt.Errorf("ROWID 输出列号超出范围")
		}
		ignored[i] = true
	}
	var original, aliases, group []string
	for i, c := range columns {
		if c == "" {
			return "", fmt.Errorf("物化视图核验列名为空")
		}
		original = append(original, Quote(c))
		aliases = append(aliases, Quote(fmt.Sprintf("DBGOLD_C%d", i)))
		if !ignored[i] {
			group = append(group, aliases[i])
		}
	}
	grouped := func(from string) string {
		prefix := ""
		suffix := ""
		if len(group) > 0 {
			prefix = strings.Join(group, ",") + ","
			suffix = " GROUP BY " + strings.Join(group, ",")
		}
		return "SELECT " + prefix + "COUNT(*) AS \"DBGOLD_N\" FROM " + from + " (" + strings.Join(aliases, ",") + ")" + suffix
	}
	a := grouped("(SELECT " + strings.Join(original, ",") + " FROM " + Qualified(schema, name) + ") AS \"DBGOLD_S\"")
	b := grouped("(" + query + ") AS \"DBGOLD_Q\"")
	return "SELECT COUNT(*) FROM (SELECT * FROM (" + a + " MINUS " + b + ") AS \"DBGOLD_L\" UNION ALL SELECT * FROM (" + b + " MINUS " + a + ") AS \"DBGOLD_R\") AS \"DBGOLD_DIFF\"", nil
}

type materializedQuerier interface {
	QueryRowContext(context.Context, string, ...any) *sql.Row
}

func CheckMaterializedBag(ctx context.Context, db materializedQuerier, schema, name, query string, columns []string, ignore []int) error {
	sql, err := MaterializedBagSQL(schema, name, query, columns, ignore)
	if err != nil {
		return err
	}
	var differences int64
	if err = db.QueryRowContext(ctx, sql).Scan(&differences); err != nil {
		return fmt.Errorf("多重集一致性查询失败: %w", err)
	}
	if differences != 0 {
		return fmt.Errorf("存储快照与定义查询的多重集不同（%d 组差异）", differences)
	}
	return nil
}

func materializedDirectRowIDs(query string, columnCount int) ([]int, error) {
	ts, err := nativeTokens(query)
	if err != nil {
		return nil, err
	}
	start, depth := 0, 0
	for start < len(ts) {
		if ts[start].value == "(" {
			depth++
		}
		if ts[start].value == ")" {
			depth--
		}
		if depth == 0 && ts[start].kind == 'i' && strings.EqualFold(ts[start].value, "SELECT") {
			break
		}
		start++
	}
	if start == len(ts) {
		return nil, fmt.Errorf("未找到 SELECT")
	}
	start++
	if start < len(ts) && (strings.EqualFold(ts[start].value, "DISTINCT") || strings.EqualFold(ts[start].value, "ALL") || strings.EqualFold(ts[start].value, "UNIQUE")) {
		start++
	}
	var items [][]sqlToken
	last := start
	for i := start; i < len(ts); i++ {
		t := ts[i]
		if t.value == "(" {
			depth++
		}
		if t.value == ")" {
			depth--
		}
		if depth == 0 && (t.value == "," || t.kind == 'i' && strings.EqualFold(t.value, "FROM")) {
			items = append(items, ts[last:i])
			last = i + 1
			if strings.EqualFold(t.value, "FROM") {
				break
			}
		}
	}
	var ids []int
	allowed := map[int]bool{}
	for i, item := range items {
		rowid := -1
		for j, t := range item {
			if (t.kind == 'i' || t.kind == 'q') && strings.EqualFold(t.value, "ROWID") {
				rowid = j
				break
			}
		}
		if rowid < 0 {
			continue
		}
		if item[rowid].kind != 'i' {
			return nil, fmt.Errorf("引号内 ROWID 可能为普通用户列，只允许直接伪列映射")
		}
		if len(items) != columnCount {
			return nil, fmt.Errorf("含 ROWID 的选择列表存在无法按列号证明的星号展开")
		}
		for j := 0; j < rowid; j++ {
			if j%2 == 0 {
				if item[j].kind != 'i' && item[j].kind != 'q' {
					return nil, fmt.Errorf("仅可映射直接 ROWID 输出，不能忽略 ROWID 表达式")
				}
			} else if item[j].value != "." {
				return nil, fmt.Errorf("仅可映射直接 ROWID 输出，不能忽略 ROWID 表达式")
			}
		}
		if rowid%2 != 0 {
			return nil, fmt.Errorf("ROWID 限定名无效")
		}
		tail := item[rowid+1:]
		if len(tail) > 0 && strings.EqualFold(tail[0].value, "AS") {
			tail = tail[1:]
		}
		if len(tail) > 1 || len(tail) == 1 && tail[0].kind != 'i' && tail[0].kind != 'q' {
			return nil, fmt.Errorf("仅可映射直接 ROWID 输出，不能忽略 ROWID 表达式")
		}
		ids = append(ids, i)
		allowed[item[rowid].start] = true
	}
	for _, token := range ts {
		if (token.kind == 'i' || token.kind == 'q') && strings.EqualFold(token.value, "ROWID") && !allowed[token.start] {
			return nil, fmt.Errorf("ROWID 出现在直接输出以外，不能证明目标物理身份变化不影响查询语义")
		}
	}
	return ids, nil
}

func (r *catalogReader) readMaterializedLogs() error {
	hasCandidate := false
	for _, o := range r.snapshot.Objects {
		if o.Kind == "materialized_view_log" || strings.HasPrefix(o.Name, "MLOG$_") {
			hasCandidate = true
		}
	}
	rows, err := r.db.QueryContext(r.ctx, `SELECT MASTER,LOG_TABLE FROM ALL_MVIEW_LOGS WHERE LOG_OWNER=? ORDER BY MASTER`, r.schema)
	type log struct{ master, storage string }
	var logs []log
	if err != nil {
		if hasCandidate {
			// Older DM8 has SYS.USER_MVIEWS but no ALL_MVIEW_LOGS. The
			// documented reserved MLOG$_ name plus exact raw PID proves this
			// relation without guessing offsets or interpreting user names.
			for _, raw := range r.raw {
				if raw.sub != "UTAB" || !strings.HasPrefix(raw.name, "MLOG$_") {
					continue
				}
				parent, ok := r.raw[raw.pid]
				if !ok || raw.name != "MLOG$_"+parent.name {
					return fmt.Errorf("物化视图日志 %s 缺少可确认的目录父关系", raw.name)
				}
				logs = append(logs, log{parent.name, raw.name})
			}
			if len(logs) == 0 {
				return fmt.Errorf("物化视图日志承载关系不可读取: %w", err)
			}
		} else {
			return nil
		}
	} else {
		for rows.Next() {
			var item log
			if err = rows.Scan(&item.master, &item.storage); err != nil {
				_ = rows.Close()
				return err
			}
			logs = append(logs, item)
		}
		err = rows.Err()
		_ = rows.Close()
		if err != nil {
			return err
		}
	}
	sort.Slice(logs, func(i, j int) bool { return logs[i].master < logs[j].master })
	for _, item := range logs {
		master, storage := item.master, item.storage
		parent := r.namedObject(master)
		if parent == nil {
			return fmt.Errorf("物化视图日志 %s 的基表 %s 不在 schema 清单中", storage, master)
		}
		parentID := parent.ID
		i := r.add(0, Object{Kind: "materialized_view_log", Name: master, Schema: r.schema, Table: master, ParentID: parentID, Dependencies: []string{parentID}})
		logicalID := r.snapshot.Objects[i].ID
		var storageID int64
		for id, raw := range r.raw {
			if raw.name == storage {
				storageID = id
				break
			}
		}
		for i := range r.snapshot.Objects {
			o := &r.snapshot.Objects[i]
			if o.Name == storage && (o.Kind == "table" || o.Kind == "materialized_view_log") {
				o.Managed = true
				o.Generated = true
				o.ParentID = logicalID
				o.Table = master
			}
		}
		r.snapshot.Objects[i].Table = master
		r.snapshot.Objects[i].ParentID = parentID
		r.snapshot.Objects[i].Dependencies = appendUnique(r.snapshot.Objects[i].Dependencies, parentID)
		for id, raw := range r.raw {
			if raw.sub == "TRIG" && raw.info1&32 != 0 && (raw.name == "MTRG$_"+master || storageID != 0 && raw.name == "MTRG_PURGE_MVLOG_"+strconv.FormatInt(storageID, 10)) {
				for _, j := range r.byRaw[id] {
					o := &r.snapshot.Objects[j]
					o.Managed = true
					o.Generated = true
					o.ParentID = logicalID
					o.Dependencies = appendUnique(o.Dependencies, logicalID)
					o.Units = nil
				}
			}
			if raw.sub == "INDEX" && raw.pid == storageID && (raw.name == "MINDEX$_"+strconv.FormatInt(storageID, 10) || raw.name == "MINDEX$_"+strconv.FormatInt(storageID, 10)+"_SEQ") {
				for _, j := range r.byRaw[id] {
					o := &r.snapshot.Objects[j]
					o.Managed = true
					o.Generated = true
					o.ParentID = logicalID
					o.Dependencies = appendUnique(o.Dependencies, logicalID)
					o.Units = nil
				}
			}
		}
	}
	return nil
}

func (r *catalogReader) materializedLogDDLName(master string) string {
	for _, raw := range r.raw {
		if raw.sub != "UTAB" || raw.name != "MLOG$_"+master {
			continue
		}
		if parent, ok := r.raw[raw.pid]; ok && parent.name == master {
			return raw.name
		}
	}
	return master
}

func (r *catalogReader) classifyMaterializedViews() error {
	hasViews := false
	for _, o := range r.snapshot.Objects {
		if o.Kind == "view" || o.Kind == "materialized_view" {
			hasViews = true
			break
		}
	}
	if !hasViews {
		return nil
	}
	// ALL_OBJECTS reports a materialized view as VIEW on supported DM8 builds;
	// SYS.USER_MVIEWS is the documented authoritative classification catalog.
	rows, err := r.db.QueryContext(r.ctx, `SELECT MVIEW_NAME FROM SYS.USER_MVIEWS WHERE SCHID=(SELECT ID FROM SYS.SYSOBJECTS WHERE TYPE$='SCH' AND NAME=?) ORDER BY MVIEW_NAME`, r.schema)
	if err != nil {
		return fmt.Errorf("无法核对物化视图完整清单: %w", err)
	}
	var names []string
	for rows.Next() {
		var name string
		if err = rows.Scan(&name); err != nil {
			_ = rows.Close()
			return err
		}
		names = append(names, name)
	}
	err = rows.Err()
	_ = rows.Close()
	if err != nil {
		return err
	}
	for _, name := range names {
		i, ok := r.index["view\x00"+name]
		if !ok {
			if _, exists := r.index["materialized_view\x00"+name]; exists {
				continue
			}
			return fmt.Errorf("物化视图 %s 在原生清单中缺失", name)
		}
		o := &r.snapshot.Objects[i]
		oldID := o.ID
		delete(r.index, "view\x00"+name)
		o.Kind = "materialized_view"
		o.ID = ObjectID(o.Schema, o.Kind, o.Name)
		r.index[o.Kind+"\x00"+name] = i
		for j := range r.snapshot.Objects {
			child := &r.snapshot.Objects[j]
			if child.ParentID == oldID {
				child.ParentID = o.ID
			}
			for k, dep := range child.Dependencies {
				if dep == oldID {
					child.Dependencies[k] = o.ID
				}
			}
		}
	}
	return nil
}

func (r *catalogReader) markManagedTree(root int64, parent string) {
	ids := map[int64]bool{root: true}
	for changed := true; changed; {
		changed = false
		for id, o := range r.raw {
			if !ids[id] && ids[o.pid] {
				ids[id] = true
				changed = true
			}
		}
	}
	for id := range ids {
		for _, i := range r.byRaw[id] {
			o := &r.snapshot.Objects[i]
			o.Managed = true
			o.ParentID = parent
			o.Units = nil
			o.Dependencies = appendUnique(o.Dependencies, parent)
		}
	}
}

func renameDDLHead(ddl, kind, schema, name string) (string, error) {
	ts, err := nativeTokens(ddl)
	if err != nil {
		return "", err
	}
	for i, t := range ts {
		if t.kind == 'i' && strings.EqualFold(t.value, kind) {
			j := i + 1
			if j >= len(ts) || ts[j].kind != 'q' && ts[j].kind != 'i' {
				return "", fmt.Errorf("原生 DDL 对象名不完整")
			}
			end := ts[j].end
			if j+2 < len(ts) && ts[j+1].value == "." {
				end = ts[j+2].end
			}
			return ddl[:ts[j].start] + Qualified(schema, name) + ddl[end:], nil
		}
	}
	return "", fmt.Errorf("原生 DDL 缺少 %s 对象头", kind)
}

func bindPrebuiltMV(ddl, schema, storage string) (string, error) {
	ts, err := nativeTokens(ddl)
	if err != nil {
		return "", err
	}
	view := -1
	for i, t := range ts {
		if strings.EqualFold(t.value, "VIEW") {
			view = i
			break
		}
	}
	if view < 1 || !strings.EqualFold(ts[view-1].value, "MATERIALIZED") {
		return "", fmt.Errorf("不是完整 CREATE MATERIALIZED VIEW")
	}
	i := view + 1
	if i >= len(ts) {
		return "", fmt.Errorf("物化视图名称缺失")
	}
	i++
	if i+1 < len(ts) && ts[i].value == "." {
		i += 2
	}
	if i < len(ts) && ts[i].value == "(" {
		end, e := matchingParen(ts, i)
		if e != nil {
			return "", e
		}
		i = end + 1
	}
	if i >= len(ts) {
		return "", fmt.Errorf("物化视图定义不完整")
	}
	headerEnd := ts[i-1].end
	as, options := -1, -1
	depth := 0
	for j := i; j < len(ts); j++ {
		t := ts[j]
		if t.value == "(" {
			depth++
		}
		if t.value == ")" {
			depth--
		}
		if depth != 0 || t.kind != 'i' {
			continue
		}
		if strings.EqualFold(t.value, "AS") {
			as = j
			break
		}
		if options < 0 && (strings.EqualFold(t.value, "REFRESH") || strings.EqualFold(t.value, "NEVER") || strings.EqualFold(t.value, "ENABLE") || strings.EqualFold(t.value, "DISABLE")) {
			options = j
		}
	}
	if as < 0 {
		return "", fmt.Errorf("物化视图缺少查询 AS")
	}
	// All auxiliary-table options are carried by the copied storage DDL. Only
	// refresh/query-rewrite options belong on the prebuilt MV declaration.
	if options < 0 {
		options = as
	}
	for j := i; j < options; {
		word := strings.ToUpper(ts[j].value)
		switch word {
		case "BUILD":
			if j+1 >= options || !strings.EqualFold(ts[j+1].value, "IMMEDIATE") && !strings.EqualFold(ts[j+1].value, "DEFERRED") {
				return "", fmt.Errorf("无法安全识别 BUILD 选项")
			}
			j += 2
		case "STORAGE":
			if j+1 >= options || ts[j+1].value != "(" {
				return "", fmt.Errorf("STORAGE 选项不完整")
			}
			end, e := matchingParen(ts, j+1)
			if e != nil {
				return "", e
			}
			j = end + 1
		case "TABLESPACE":
			j += 2
		case "PARTITION": // Partition definitions are already on the storage
			// table. A top-level clause may contain several nested key/value lists.
			j++
			for j < options {
				if ts[j].value == "(" {
					end, e := matchingParen(ts, j)
					if e != nil {
						return "", e
					}
					j = end + 1
				} else {
					j++
				}
			}
		case "FOR": // Original prebuilt MV: replace the entire old binding.
			j++
			for j < options && !strings.EqualFold(ts[j].value, "TABLE") {
				j++
			}
			if j >= options {
				return "", fmt.Errorf("原 PREBUILT TABLE 绑定不完整")
			}
			j++
			if j < options && (strings.EqualFold(ts[j].value, "WITH") || strings.EqualFold(ts[j].value, "WITHOUT")) {
				j += 3
			}
		default:
			return "", fmt.Errorf("辅助表选项 %s 无法在保留快照时安全重建", word)
		}
	}
	return ddl[:headerEnd] + " FOR " + Qualified(schema, storage) + " ON PREBUILT TABLE " + ddl[ts[options].start:], nil
}
func matchingParen(ts []sqlToken, open int) (int, error) {
	depth := 0
	for i := open; i < len(ts); i++ {
		if ts[i].value == "(" {
			depth++
		}
		if ts[i].value == ")" {
			depth--
			if depth == 0 {
				return i, nil
			}
		}
	}
	return 0, fmt.Errorf("原生 DDL 括号不完整")
}
